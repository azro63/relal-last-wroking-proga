CREATE TABLE IF NOT EXISTS game_snapshots (
                                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              clock_time  INTEGER      NOT NULL,
                                              game_time   INTEGER,
                                              is_daytime  BOOLEAN,
                                              win_team    VARCHAR(16),
    captured_at TIMESTAMP(6) NOT NULL
    );

CREATE INDEX IF NOT EXISTS idx_clock_time  ON game_snapshots (clock_time);
CREATE INDEX IF NOT EXISTS idx_captured_at ON game_snapshots (captured_at);